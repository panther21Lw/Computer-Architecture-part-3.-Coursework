#ifndef DRIVERS_NVIC_H_
#define DRIVERS_NVIC_H_

#include <stdint.h>

#include "memory_map.h"

// NVIC registers
typedef struct {
	// the first register, ISER0, has offset 0x100
	// so placing RESERVED area here
	// offset: 0x100, each register has 4 bytes, so 0x100 == 256 / 4 = 64 reserved registers
	// IT WAS THE TYPEO' IN DOCUMENTATION... no need to insert starting reserved area
	/**
	 * https://community.st.com/stm32-mpus-embedded-software-and-solutions-46/
	 * invalid-addresses-of-nvic-s-registers-in-stm32-cortex-m4-mcus-
	 * and-mpus-programming-manual-50605?utm_source=chatgpt.com
	 */

	volatile uint32_t ISER[8];		/* Interrupt set-enable register x (x = 0 to 7)		*/
	// Base of NVIC_ICER0 is 0XE000E180, base of NVIC_ISER0 is 0xE000E100
	// (0x80 - 0x20) / 4 = 0x18	(d24)
		uint32_t RESERVED0[24];
	volatile uint32_t ICER[8];		/* Interrupt clear-enable register x (x = 0 to 7) 	*/
		uint32_t RESERVED1[24];
	volatile uint32_t ISPR[8];		/* Interrupt set-pending register x (x = 0 to 7)	*/
		uint32_t RESERVED2[24];
	volatile uint32_t ICPR[8];		/* Interrupt clear-pending register x (x = 0 to 7)	*/
		uint32_t RESERVED3[24];
	volatile uint32_t IABR[8];		/* Interrupt active bit register x (x = 0 to 7)		*/
		uint32_t RESERVED4[56];
	volatile uint8_t IPR[240];		/* Interrupt priority register x (x = 0 to 59)		*/
		uint32_t RESERVED5[644];
	volatile uint32_t STIR;			/* Software trigger interrupt register				*/
} NVIC_TypeDef;

#define NVIC		((NVIC_TypeDef *) NVIC_BASE)

typedef enum {
	/*
	 * there are a lot of interrupt sources in Vector table
	 * but we will use only interrupts generated by USART2
	 */
	USART2_IRQn		= 38UL		/* USART2 interrupt position	*/
} IRQn_t;

/**
 * This enumeration provides interrupt priorities.
 * The lower the number, the higher the priority.
 */
typedef enum {
	INTRPT_PRIOR_0	= 0x00UL,	/*	Priority level 0. HIGHEST PRIORITY	*/
	INTRPT_PRIOR_1	= 0x01UL,	/*	Priority level 1					*/
	INTRPT_PRIOR_2	= 0x02UL,	/*	Priority level 2					*/
	INTRPT_PRIOR_3	= 0x03UL,	/*	Priority level 3					*/
	INTRPT_PRIOR_4	= 0x04UL,	/*	Priority level 4					*/
	INTRPT_PRIOR_5	= 0x05UL,	/*	Priority level 5					*/
	INTRPT_PRIOR_6	= 0x06UL,	/*	Priority level 6					*/
	INTRPT_PRIOR_7	= 0x07UL,	/*	Priority level 7					*/
	INTRPT_PRIOR_8	= 0x08UL,	/*	Priority level 8					*/
	INTRPT_PRIOR_9	= 0x09UL,	/*	Priority level 9					*/
	INTRPT_PRIOR_10	= 0x0AUL,	/*	Priority level 10					*/
	INTRPT_PRIOR_11	= 0x0BUL,	/*	Priority level 11					*/
	INTRPT_PRIOR_12	= 0x0CUL,	/*	Priority level 12					*/
	INTRPT_PRIOR_13	= 0x0DUL,	/*	Priority level 13					*/
	INTRPT_PRIOR_14	= 0x0EUL,	/*	Priority level 14					*/
	INTRPT_PRIOR_15	= 0x0FUL,	/*	Priority level 15. LOWEST PRIORITY	*/
} IRQn_Prior_t;

/**
 * This function enables the interrupt line.
 */
static inline void NVIC_EnableIRQ(IRQn_t irq_n) {
	NVIC->ISER[(uint32_t)irq_n / 32U] = (1UL << ((uint32_t)irq_n % 32U));
}

/**
 * This function disables the interrupt line.
 */
static inline void NVIC_DisableIRQ(IRQn_t irq_n) {
	NVIC->ICER[(uint32_t)irq_n / 32U] = (1UL << ((uint32_t)irq_n % 32U));
}

/**
 * This function sets the priority for the interrupt line.
 */
static inline void NVIC_SetPriority(IRQn_t irq_n, IRQn_Prior_t priority) {
	NVIC->IPR[(uint32_t)irq_n] = (((uint32_t)priority & 0x0FUL) << 4U);
}

/**
 * This function return the priority of the interrupt line.
 */
uint32_t NVIC_GetPriority(IRQn_t irq_n);

#endif /* DRIVERS_NVIC_H_ */
