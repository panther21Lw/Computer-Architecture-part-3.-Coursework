#ifndef MEMORY_MAP_H_
#define MEMORY_MAP_H_

#define PERIPH_BASE 			(0x40000000UL)					// 0x4000 0000
#define APB1PERIPH_BASE			(PERIPH_BASE + 0x0000000UL)		// 0x4000 0000
#define APB2PERIPH_BASE			(PERIPH_BASE + 0x00010000UL)	// 0x4001 0000
#define AHB1PERIPH_BASE			(PERIPH_BASE + 0x00020000UL)	// 0x4002 0000
#define AHB2PERIPH_BASE			(PERIPH_BASE + 0x10000000UL)	// 0x5000 0000


#define FLASH_R_BASE			(AHB1PERIPH_BASE + 0x3C00UL)	// 0x4002 3C00
#define RCC_BASE				(AHB1PERIPH_BASE + 0x3800UL)	// 0x4002 3800
#define GPIOB_BASE				(AHB1PERIPH_BASE + 0x0400UL)	// 0x4002 0400
#define GPIOA_BASE				(AHB1PERIPH_BASE + 0x0000UL)	// 0x4002 0000

#define POWER_BASE				(APB1PERIPH_BASE + 0x7000UL)	// 0x4000 7000
#define USART2_BASE				(APB1PERIPH_BASE + 0x4400UL)	// 0x4000 4400


#define CORE_PERIPH_BASE		(0xE0000000UL)					// 0xE000 0000
#define NVIC_BASE				(CORE_PERIPH_BASE + 0xE100UL)   // 0xE000 E100

#endif /* MEMORY_MAP_H_ */
